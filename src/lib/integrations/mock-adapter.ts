  async addJiraWorklog(
    issueKey: string,
    timeSpent: string,
    comment: string,
    started?: string
  ): Promise<{ success: boolean; worklogId?: string; message: string }> {
    const id = `wl-${Date.now()}`;
    const tickets = await this.getJiraTickets();
    const matchingTicket = tickets.find((t) => t.key.toUpperCase() === issueKey.toUpperCase());

    let totalSec = 0;
    const hourMatch = timeSpent.match(/(\d+(?:\.\d+)?)\s*h/i);
    const minMatch = timeSpent.match(/(\d+)\s*m/i);
    if (hourMatch) totalSec += parseFloat(hourMatch[1]) * 3600;
    if (minMatch) totalSec += parseInt(minMatch[1], 10) * 60;
    if (!hourMatch && !minMatch) {
      const num = parseFloat(timeSpent);
      if (!isNaN(num)) totalSec = num * 3600;
    }
    const timeSpentSeconds = totalSec || 3600;

    const newWorklog: JiraWorklog = {
      id,
      issueKey,
      issueTitle: matchingTicket?.title || `Jira Ticket ${issueKey}`,
      timeSpent,
      timeSpentSeconds,
      author: "Muskan Gupta",
      comment,
      started: started || new Date().toISOString(),
      source: "manual",
      status: "logged",
      prNumber: matchingTicket?.prNumber,
      prUrl: matchingTicket?.prUrl,
      jiraUrl: matchingTicket?.jiraUrl || `https://amla.atlassian.net/browse/${issueKey}`,
    };

    this.mockWorklogs.unshift(newWorklog);
    // Remove any draft associated with this ticket
    this.mockDrafts = this.mockDrafts.filter((d) => d.issueKey !== issueKey);

    return {
      success: true,
      worklogId: id,
      message: `Successfully logged ${timeSpent} to ${issueKey} in Jira.`,
    };
  }

  async deleteJiraWorklog(
    issueKey: string,
    worklogId: string
  ): Promise<{ success: boolean; message: string }> {
    const cleanId = worklogId.replace(/^wl-/, "").trim();
    this.mockWorklogs = this.mockWorklogs.filter(
      (w) => w.id !== worklogId && w.id !== cleanId && w.id !== `wl-${cleanId}`
    );
    return {
      success: true,
      message: `Successfully deleted worklog from ${issueKey}.`,
    };
  }

